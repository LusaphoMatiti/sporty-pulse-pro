export type ExercisePlan = {
  exerciseName: string;
  order: number;
  beginnerSets: number;
  beginnerReps: number;
  intermediateSets: number;
  intermediateReps: number;
  advancedSets: number;
  advancedReps: number;
  restSeconds: number;
};

export type SessionPlan = {
  sessionNumber: number;
  focus: string;
  exercises: ExercisePlan[];
};

export type ProgramPlan = {
  name: string;
  description: string;
  muscleGroup: "UPPER" | "LOWER" | "CORE" | "FULLBODY";
  durationWeeks: number;
  sessionsPerWeek: number;
  tier: "FREE" | "EQUIPMENT";
  equipmentName: string | null;
  templateType:
    | "FULL_BODY_RESTORE"
    | "FULL_BODY_STRENGTH"
    | "CONDITIONING_CIRCUIT"
    | "PUSH_PULL_LEGS"
    | "ADVANCED_PPL"
    | "STRENGTH_HIIT"
    | "PERFORMANCE_CONDITIONING";
  identityTarget: "REBUILD" | "OPERATOR" | "EXECUTIVE_PERFORMANCE" | null;
  goalTarget: "LOSE_WEIGHT" | "BUILD_MUSCLE" | "GET_FIT" | null;
  environmentTarget: "HOME_BODYWEIGHT" | "HOME_EQUIPMENT" | "GYM" | "ANY";
  sessionDurationMin: string;
  difficulty: "Beginner" | "Intermediate" | "Advanced";
  impactLevel: "LOW" | "MEDIUM" | "HIGH";
  sessions: SessionPlan[];
};

// ─────────────────────────────────────────────
// HELPER — generates N sessions repeating the pattern
// ─────────────────────────────────────────────
function repeat(
  pattern: Omit<SessionPlan, "sessionNumber">[],
  totalSessions: number,
): SessionPlan[] {
  const sessions: SessionPlan[] = [];
  for (let i = 0; i < totalSessions; i++) {
    const template = pattern[i % pattern.length];
    sessions.push({ ...template, sessionNumber: i + 1 });
  }
  return sessions;
}

